import { useEffect, useMemo, useState } from "react";
import { MdSearch, MdDownload } from "react-icons/md";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import toast from "react-hot-toast";
import { getOrderReport, AuthService } from "../../api";
import { formatCurrency } from "../../constants/pos";
import Sidebar from "../../components/dashboard/Sidebar";
import Header from "../../components/dashboard/Header";

const STATUS_BADGES = {
  completed: "bg-green-100 text-green-700",
  pending: "bg-yellow-100 text-yellow-700",
  processing: "bg-blue-100 text-blue-700",
  cancelled: "bg-gray-200 text-gray-700",
  failed: "bg-red-100 text-red-700",
};

const PAYMENT_BADGES = {
  paid: "bg-green-100 text-green-700",
  pending: "bg-yellow-100 text-yellow-700",
  failed: "bg-red-100 text-red-700",
  refunded: "bg-purple-100 text-purple-700",
};

// Plain-text amount for jsPDF output
const formatPlainAmount = (amount) => `$${Number(amount || 0).toFixed(2)}`;

const capitalize = (value) =>
  value ? value.charAt(0).toUpperCase() + value.slice(1) : "-";

const formatDate = (value) =>
  value ? new Date(value).toLocaleString("en-IN") : "-";

const OrderReportsPage = () => {
  const [orders, setOrders] = useState([]);
  const [loading, setLoading] = useState(true);
  const [search, setSearch] = useState("");
  const [status, setStatus] = useState("");
  const [fromDate, setFromDate] = useState("");
  const [toDate, setToDate] = useState("");

  useEffect(() => {
    let cancelled = false;

    const fetchReport = async () => {
      setLoading(true);
      try {
        const data = await getOrderReport({ from: fromDate, to: toDate });
        if (!cancelled) setOrders(data.orders || []);
      } catch (error) {
        if (!cancelled) toast.error(error.message || "Failed to load order report");
      } finally {
        if (!cancelled) setLoading(false);
      }
    };

    fetchReport();
    return () => {
      cancelled = true;
    };
  }, [fromDate, toDate]);

  const filteredOrders = useMemo(() => {
    const term = search.trim().toLowerCase();
    return orders.filter((order) => {
      if (status && order.status !== status) return false;
      if (!term) return true;
      return (
        order.orderNumber?.toLowerCase().includes(term) ||
        order.customerName?.toLowerCase().includes(term) ||
        order.customerPhone?.toLowerCase().includes(term) ||
        order.billedBy?.toLowerCase().includes(term)
      );
    });
  }, [orders, search, status]);

  const totals = useMemo(
    () =>
      filteredOrders.reduce(
        (sum, order) => {
          const isCompleted = order.status === "completed";
          return {
            completed: sum.completed + (isCompleted ? 1 : 0),
            quantity: sum.quantity + (isCompleted ? order.totalQuantity || 0 : 0),
            revenue: sum.revenue + (isCompleted ? order.total || 0 : 0),
            amount: sum.amount + (order.total || 0),
          };
        },
        { completed: 0, quantity: 0, revenue: 0, amount: 0 },
      ),
    [filteredOrders],
  );

  const handleDownloadPdf = () => {
    if (filteredOrders.length === 0) {
      toast.error("No orders to export");
      return;
    }

    const doc = new jsPDF({ orientation: "landscape" });
    const pageWidth = doc.internal.pageSize.getWidth();
    const navy = [26, 37, 53];
    const gray = [108, 117, 125];
    const user = AuthService.isFranchise()
      ? AuthService.getFranchise()
      : AuthService.getUser();

    doc.setFontSize(18);
    doc.setTextColor(...navy);
    doc.text("Order Report", 14, 20);

    doc.setFontSize(9);
    doc.setTextColor(...gray);
    const meta = [`Generated on ${new Date().toLocaleString("en-IN")}`];
    if (user?.name) meta.push(`Generated by ${user.name}`);
    if (fromDate || toDate) {
      meta.push(`Period: ${fromDate || "Start"} to ${toDate || "Today"}`);
    }
    if (status) meta.push(`Status: ${capitalize(status)}`);
    doc.text(meta.join("   |   "), 14, 27);

    doc.text(
      `Orders: ${filteredOrders.length}   |   Completed: ${totals.completed}   |   Items Sold: ${totals.quantity}   |   Revenue: ${formatPlainAmount(totals.revenue)}`,
      14,
      33,
    );

    autoTable(doc, {
      startY: 39,
      head: [[
        "#",
        "Order No.",
        "Date",
        "Customer",
        "Billed By",
        "Items",
        "Qty",
        "Payment",
        "Payment Status",
        "Status",
        "Total",
      ]],
      body: filteredOrders.map((order, index) => [
        String(index + 1),
        order.orderNumber || "-",
        formatDate(order.createdAt),
        order.customerName || "Walk-in",
        order.billedBy || "-",
        String(order.itemCount ?? 0),
        String(order.totalQuantity ?? 0),
        capitalize(order.paymentMethod),
        capitalize(order.paymentStatus),
        capitalize(order.status),
        formatPlainAmount(order.total),
      ]),
      foot: [[
        "", "", "", "", "", "Total", "", "", "", "",
        formatPlainAmount(totals.amount),
      ]],
      styles: { fontSize: 8 },
      headStyles: { fillColor: navy, textColor: [255, 255, 255], fontStyle: "bold" },
      footStyles: { fillColor: [248, 249, 250], textColor: navy, fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 9 },
        5: { halign: "right" },
        6: { halign: "right" },
        10: { halign: "right" },
      },
      theme: "grid",
      didDrawPage: () => {
        const pageHeight = doc.internal.pageSize.getHeight();
        doc.setFontSize(8);
        doc.setTextColor(173, 181, 189);
        doc.text("Powered by Exostock", 14, pageHeight - 10);
        doc.text(
          `Page ${doc.internal.getNumberOfPages()}`,
          pageWidth - 14,
          pageHeight - 10,
          { align: "right" },
        );
      },
    });

    doc.save(`order-report-${new Date().toISOString().slice(0, 10)}.pdf`);
  };

  return (
    <div className="flex bg-[#F8F9FA] min-h-screen">
      <Sidebar />

      <div className="flex-1 ml-0 lg:ml-[300px]">
        <Header />

        <main className="p-4 sm:p-6 lg:p-8">
          {/* Header */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-8">
            <div>
              <h1 className="text-[28px] font-bold text-[#212529]">
                Order Reports
              </h1>
              <p className="text-[14px] text-[#6C757D] mt-1">
                All orders with items, payment and status details.
              </p>
            </div>

            <button
              type="button"
              onClick={handleDownloadPdf}
              disabled={loading || filteredOrders.length === 0}
              className="inline-flex items-center justify-center gap-2 h-11 px-5 rounded-lg bg-[#0d5b96] text-white text-sm font-semibold hover:bg-[#0a4a7a] disabled:opacity-50 disabled:cursor-not-allowed"
            >
              <MdDownload className="text-lg" />
              Download PDF
            </button>
          </div>

          {/* Summary */}
          <div className="grid grid-cols-1 sm:grid-cols-2 xl:grid-cols-4 gap-4 mb-6">
            <SummaryCard label="Total Orders" value={filteredOrders.length} />
            <SummaryCard label="Completed Orders" value={totals.completed} />
            <SummaryCard label="Items Sold" value={totals.quantity} />
            <SummaryCard label="Revenue" value={formatCurrency(totals.revenue)} />
          </div>

          {/* Card */}
          <div className="bg-white border border-[#DEE2E6] rounded-2xl shadow-sm overflow-hidden">
            {/* Filters */}
            <div className="p-5 border-b border-[#DEE2E6] flex flex-col lg:flex-row lg:items-end gap-4">
              <div className="relative w-full lg:max-w-sm">
                <MdSearch className="absolute left-3 top-3 text-[#ADB5BD] text-lg" />
                <input
                  type="text"
                  placeholder="Search by order no., customer, or user..."
                  value={search}
                  onChange={(e) => setSearch(e.target.value)}
                  className="w-full h-11 pl-10 pr-4 border border-[#DEE2E6] rounded-lg text-sm focus:outline-none focus:border-black"
                />
              </div>

              <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 lg:ml-auto">
                <label className="text-xs text-[#6C757D]">
                  Status
                  <select
                    value={status}
                    onChange={(e) => setStatus(e.target.value)}
                    className="mt-1 w-full h-11 px-3 border border-[#DEE2E6] rounded-lg text-sm text-[#212529] bg-white focus:outline-none focus:border-black"
                  >
                    <option value="">All</option>
                    <option value="completed">Completed</option>
                    <option value="pending">Pending</option>
                    <option value="processing">Processing</option>
                    <option value="cancelled">Cancelled</option>
                    <option value="failed">Failed</option>
                  </select>
                </label>

                <label className="text-xs text-[#6C757D]">
                  From
                  <input
                    type="date"
                    value={fromDate}
                    max={toDate || undefined}
                    onChange={(e) => setFromDate(e.target.value)}
                    className="mt-1 w-full h-11 px-3 border border-[#DEE2E6] rounded-lg text-sm text-[#212529] focus:outline-none focus:border-black"
                  />
                </label>

                <label className="text-xs text-[#6C757D]">
                  To
                  <input
                    type="date"
                    value={toDate}
                    min={fromDate || undefined}
                    onChange={(e) => setToDate(e.target.value)}
                    className="mt-1 w-full h-11 px-3 border border-[#DEE2E6] rounded-lg text-sm text-[#212529] focus:outline-none focus:border-black"
                  />
                </label>
              </div>
            </div>

            {/* Table */}
            <div className="overflow-x-auto">
              <table className="w-full">
                <thead className="bg-[#F8F9FA]">
                  <tr>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Order No.</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Date</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Customer</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Billed By</th>
                    <th className="px-5 py-4 text-center text-sm font-semibold">Items</th>
                    <th className="px-5 py-4 text-center text-sm font-semibold">Qty</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Payment</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Status</th>
                    <th className="px-5 py-4 text-right text-sm font-semibold">Total</th>
                  </tr>
                </thead>

                <tbody>
                  {loading ? (
                    <tr>
                      <td colSpan="9" className="py-10 text-center text-[#6C757D]">
                        Loading order report...
                      </td>
                    </tr>
                  ) : filteredOrders.length === 0 ? (
                    <tr>
                      <td colSpan="9" className="py-10 text-center text-[#6C757D]">
                        No orders found.
                      </td>
                    </tr>
                  ) : (
                    filteredOrders.map((order) => (
                      <tr
                        key={order.id}
                        className="border-t border-[#F1F3F5] hover:bg-[#FAFAFA]"
                      >
                        <td className="px-5 py-4 text-sm font-semibold">{order.orderNumber}</td>
                        <td className="px-5 py-4 text-sm whitespace-nowrap">
                          {formatDate(order.createdAt)}
                        </td>
                        <td className="px-5 py-4 text-sm">
                          <div>{order.customerName || "Walk-in"}</div>
                          {order.customerPhone && (
                            <div className="text-xs text-[#6C757D]">{order.customerPhone}</div>
                          )}
                        </td>
                        <td className="px-5 py-4 text-sm">{order.billedBy || "-"}</td>
                        <td className="px-5 py-4 text-sm text-center">{order.itemCount}</td>
                        <td className="px-5 py-4 text-sm text-center font-semibold">
                          {order.totalQuantity}
                        </td>
                        <td className="px-5 py-4 text-sm">
                          <div className="flex flex-col items-start gap-1">
                            <span>{capitalize(order.paymentMethod)}</span>
                            <span
                              className={`inline-flex px-2 py-0.5 rounded-full text-xs font-semibold ${PAYMENT_BADGES[order.paymentStatus] || "bg-gray-100 text-gray-700"}`}
                            >
                              {capitalize(order.paymentStatus)}
                            </span>
                          </div>
                        </td>
                        <td className="px-5 py-4">
                          <span
                            className={`inline-flex px-3 py-1 rounded-full text-xs font-semibold ${STATUS_BADGES[order.status] || "bg-gray-100 text-gray-700"}`}
                          >
                            {capitalize(order.status)}
                          </span>
                        </td>
                        <td className="px-5 py-4 text-sm text-right font-semibold whitespace-nowrap">
                          {formatCurrency(order.total || 0)}
                        </td>
                      </tr>
                    ))
                  )}
                </tbody>
              </table>
            </div>
          </div>
        </main>
      </div>
    </div>
  );
};

const SummaryCard = ({ label, value }) => (
  <div className="bg-white border border-[#DEE2E6] rounded-2xl shadow-sm p-5">
    <p className="text-[13px] text-[#6C757D]">{label}</p>
    <p className="text-[24px] font-bold text-[#212529] mt-1">{value}</p>
  </div>
);

export default OrderReportsPage;
