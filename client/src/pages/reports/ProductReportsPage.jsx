import { useEffect, useMemo, useState } from "react";
import { MdSearch, MdDownload } from "react-icons/md";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import toast from "react-hot-toast";
import { getProductReport, AuthService } from "../../api";
import Sidebar from "../../components/dashboard/Sidebar";
import Header from "../../components/dashboard/Header";

const getStockStatus = (product) => {
  if (product.availableStock <= 0) {
    return { label: "Out of Stock", className: "bg-red-100 text-red-700" };
  }
  if (product.availableStock <= (product.lowStockThreshold ?? 5)) {
    return { label: "Low Stock", className: "bg-orange-100 text-orange-700" };
  }
  return { label: "In Stock", className: "bg-green-100 text-green-700" };
};

const ProductReportsPage = () => {
  const [products, setProducts] = useState([]);
  const [loading, setLoading] = useState(true);
  const [search, setSearch] = useState("");

  useEffect(() => {
    const fetchReport = async () => {
      try {
        const data = await getProductReport();
        setProducts(data.products || []);
      } catch (error) {
        toast.error(error.message || "Failed to load product report");
      } finally {
        setLoading(false);
      }
    };

    fetchReport();
  }, []);

  const filteredProducts = useMemo(() => {
    const term = search.trim().toLowerCase();
    if (!term) return products;
    return products.filter(
      (product) =>
        product.name?.toLowerCase().includes(term) ||
        product.sku?.toLowerCase().includes(term) ||
        product.category?.name?.toLowerCase().includes(term),
    );
  }, [products, search]);

  const totals = useMemo(
    () =>
      filteredProducts.reduce(
        (sum, product) => ({
          available: sum.available + (product.availableStock || 0),
          used: sum.used + (product.usedStock || 0),
        }),
        { available: 0, used: 0 },
      ),
    [filteredProducts],
  );

  const handleDownloadPdf = () => {
    if (filteredProducts.length === 0) {
      toast.error("No products to export");
      return;
    }

    const doc = new jsPDF();
    const navy = [26, 37, 53];
    const gray = [108, 117, 125];
    const user = AuthService.isFranchise()
      ? AuthService.getFranchise()
      : AuthService.getUser();

    doc.setFontSize(18);
    doc.setTextColor(...navy);
    doc.text("Product Stock Report", 14, 20);

    doc.setFontSize(9);
    doc.setTextColor(...gray);
    doc.text(`Generated on ${new Date().toLocaleString()}`, 14, 27);
    if (user?.name) {
      doc.text(`Generated by ${user.name}`, 14, 32);
    }

    autoTable(doc, {
      startY: 38,
      head: [["SR NO", "Product", "SKU", "Category", "Available Stock", "Used Stock", "Status"]],
      body: filteredProducts.map((product, index) => [
        String(index + 1),
        product.name || "-",
        product.sku || "-",
        product.category?.name || "-",
        String(product.availableStock ?? 0),
        String(product.usedStock ?? 0),
        getStockStatus(product).label,
      ]),
      foot: [["", "", "", "Total", String(totals.available), String(totals.used), ""]],
      styles: { fontSize: 9 },
      headStyles: { fillColor: navy, textColor: [255, 255, 255], fontStyle: "bold" },
      footStyles: { fillColor: [248, 249, 250], textColor: navy, fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 10 },
        4: { halign: "right" },
        5: { halign: "right" },
      },
      theme: "grid",
      didDrawPage: () => {
        const pageHeight = doc.internal.pageSize.getHeight();
        doc.setFontSize(8);
        doc.setTextColor(173, 181, 189);
        doc.text("Powered by Exostock", 14, pageHeight - 10);
        doc.text(
          `Page ${doc.internal.getNumberOfPages()}`,
          196,
          pageHeight - 10,
          { align: "right" },
        );
      },
    });

    doc.save(`product-report-${new Date().toISOString().slice(0, 10)}.pdf`);
  };

  return (
    <div className="flex bg-[#F8F9FA] min-h-screen">
      <Sidebar />

      <div className="flex-1 ml-0 lg:ml-[300px]">
        <Header />

        <main className="p-4 sm:p-6 lg:p-8">
          {/* Header */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-8">
            <div>
              <h1 className="text-[28px] font-bold text-[#212529]">
                Product Reports
              </h1>
              <p className="text-[14px] text-[#6C757D] mt-1">
                Available and used stock for all your products.
              </p>
            </div>

            <button
              type="button"
              onClick={handleDownloadPdf}
              disabled={loading || filteredProducts.length === 0}
              className="inline-flex items-center justify-center gap-2 h-11 px-5 rounded-lg bg-[#0d5b96] text-white text-sm font-semibold hover:bg-[#0a4a7a] disabled:opacity-50 disabled:cursor-not-allowed"
            >
              <MdDownload className="text-lg" />
              Download PDF
            </button>
          </div>

          {/* Summary */}
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 mb-6">
            <SummaryCard label="Total Products" value={filteredProducts.length} />
            <SummaryCard label="Total Available Stock" value={totals.available} />
            <SummaryCard label="Total Used Stock" value={totals.used} />
          </div>

          {/* Card */}
          <div className="bg-white border border-[#DEE2E6] rounded-2xl shadow-sm overflow-hidden">
            {/* Search */}
            <div className="p-5 border-b border-[#DEE2E6]">
              <div className="relative max-w-sm">
                <MdSearch className="absolute left-3 top-3 text-[#ADB5BD] text-lg" />
                <input
                  type="text"
                  placeholder="Search by product, SKU, or category..."
                  value={search}
                  onChange={(e) => setSearch(e.target.value)}
                  className="w-full h-11 pl-10 pr-4 border border-[#DEE2E6] rounded-lg text-sm focus:outline-none focus:border-black"
                />
              </div>
            </div>

            {/* Table */}
            <div className="overflow-x-auto">
              <table className="w-full">
                <thead className="bg-[#F8F9FA]">
                  <tr>
                    <th className="px-5 py-4 text-left text-sm font-semibold">SR NO</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Product</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">SKU</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Category</th>
                    <th className="px-5 py-4 text-center text-sm font-semibold">Available Stock</th>
                    <th className="px-5 py-4 text-center text-sm font-semibold">Used Stock</th>
                    <th className="px-5 py-4 text-left text-sm font-semibold">Status</th>
                  </tr>
                </thead>

                <tbody>
                  {loading ? (
                    <tr>
                      <td colSpan="7" className="py-10 text-center text-[#6C757D]">
                        Loading product report...
                      </td>
                    </tr>
                  ) : filteredProducts.length === 0 ? (
                    <tr>
                      <td colSpan="7" className="py-10 text-center text-[#6C757D]">
                        No products found.
                      </td>
                    </tr>
                  ) : (
                    filteredProducts.map((product, index) => {
                      const status = getStockStatus(product);
                      return (
                        <tr
                          key={product.id}
                          className="border-t border-[#F1F3F5] hover:bg-[#FAFAFA]"
                        >
                          <td className="px-5 py-4 text-sm text-[#6C757D]">{index + 1}</td>
                          <td className="px-5 py-4 text-sm font-semibold">{product.name}</td>
                          <td className="px-5 py-4 text-sm">{product.sku}</td>
                          <td className="px-5 py-4 text-sm">{product.category?.name || "-"}</td>
                          <td className="px-5 py-4 text-sm text-center font-semibold">
                            {product.availableStock}
                          </td>
                          <td className="px-5 py-4 text-sm text-center font-semibold">
                            {product.usedStock}
                          </td>
                          <td className="px-5 py-4">
                            <span
                              className={`inline-flex px-3 py-1 rounded-full text-xs font-semibold ${status.className}`}
                            >
                              {status.label}
                            </span>
                          </td>
                        </tr>
                      );
                    })
                  )}
                </tbody>
              </table>
            </div>
          </div>
        </main>
      </div>
    </div>
  );
};

const SummaryCard = ({ label, value }) => (
  <div className="bg-white border border-[#DEE2E6] rounded-2xl shadow-sm p-5">
    <p className="text-[13px] text-[#6C757D]">{label}</p>
    <p className="text-[24px] font-bold text-[#212529] mt-1">{value}</p>
  </div>
);

export default ProductReportsPage;
